const NS = 'http://schemas.datacontract.org/2004/07/ThreatModeling.Model';
const minimalModel = (inner: string, ns: string = NS) =>
  `<ThreatModel xmlns="${ns}">` +
  '<DrawingSurfaceList><DrawingSurfaceModel><Guid>11111111-1111-1111-1111-111111111111</Guid>' +
  '<Header>Empty Diagram</Header></DrawingSurfaceModel></DrawingSurfaceList>' +
  '<MetaInformation><ThreatModelName>My Model</ThreatModelName></MetaInformation>' +
  `${inner}</ThreatModel>`;
const validMinimal = minimalModel('<Version>4.3</Version>');

describe('parseTmtModel - minimal valid model', () => {
  const model = parseTmtModel(validMinimal);

  test('parses a minimal model and marks a surface with no elements as empty', () => {
    expect(model.surfaces).toEqual([
      { guid: '11111111-1111-1111-1111-111111111111', name: 'Empty Diagram', isEmpty: true },
    ]);
    expect(model.metadata.threatModelName).toBe('My Model');
    expect(model.threats).toEqual([]);
    expect(model.elementNames).toEqual({});
  });

  test('returns surface names without surrounding whitespace', () => {
    const padded = parseTmtModel(validMinimal.replace('<Header>Empty Diagram</Header>', '<Header>  Empty Diagram \n</Header>'));
    expect(padded.surfaces[0].name).toBe('Empty Diagram');
  });

  test('keeps an element named by an untrusted __proto__ GUID as plain data', () => {
    const xml = `<ThreatModel xmlns="${NS}"><DrawingSurfaceList><DrawingSurfaceModel><Guid>s</Guid><Header>D</Header>`
      + '<Borders><KeyValueOfguidanyType><Key>__proto__</Key><Value><Guid>__proto__</Guid><Properties>'
      + '<anyType><DisplayName>Name</DisplayName><Value>Evil</Value></anyType></Properties></Value>'
      + '</KeyValueOfguidanyType></Borders></DrawingSurfaceModel></DrawingSurfaceList><Version>4.3</Version></ThreatModel>';
    const parsed = parseTmtModel(xml);
    expect(parsed.elementNames.__proto__).toBe('Evil');
    expect(({} as Record<string, unknown>).Evil).toBeUndefined();
    expect(Object.getPrototypeOf(parsed.elementNames)).toBeNull();
  });
});

describe('parseTmtModel - rejects invalid input (imports nothing)', () => {
  test('empty input', () => {
    expect(() => parseTmtModel('')).toThrow('Empty');
  });

  test('oversized input', () => {
    expect(() => parseTmtModel(validMinimal, { maxChars: 10 })).toThrow('maximum allowed size');
  });

  test('DOCTYPE declaration', () => {
    expect(() => parseTmtModel(`<!DOCTYPE x>${validMinimal}`)).toThrow('DOCTYPE or ENTITY');
  });

  test('ENTITY declaration (XXE payload)', () => {
    const xxe = `<!DOCTYPE foo [<!ENTITY xxe SYSTEM "file:///etc/passwd">]>${validMinimal}`;
    expect(() => parseTmtModel(xxe)).toThrow('DOCTYPE or ENTITY');
  });

  test('wrong root element', () => {
    expect(() => parseTmtModel(`<NotThreatModel xmlns="${NS}"><Version>4.3</Version></NotThreatModel>`)).toThrow('Not a TMT');
  });

  test('foreign namespace', () => {
    expect(() => parseTmtModel(minimalModel('<Version>4.3</Version>', 'http://evil.example/ns'))).toThrow('Not a TMT');
  });

  test('malformed XML', () => {
    expect(() => parseTmtModel(`<ThreatModel xmlns="${NS}"><Version>4.3</Version><Unclosed></ThreatModel>`)).toThrow('Malformed');
  });

  test('absent version', () => {
    expect(() => parseTmtModel(minimalModel(''))).toThrow('Unsupported');
  });

  test('empty version', () => {
    expect(() => parseTmtModel(minimalModel('<Version/>'))).toThrow('Unsupported');
  });

  test('unsupported version 4.2', () => {
    expect(() => parseTmtModel(minimalModel('<Version>4.2</Version>'))).toThrow('Unsupported');
  });

  test('threat with a non-integer Id', () => {
    const xml = minimalModel(
      '<Version>4.3</Version><ThreatInstances><KeyValueOfstringThreatX><Key>k</Key>' +
        '<Value><Id>not-a-number</Id></Value></KeyValueOfstringThreatX></ThreatInstances>',
    );
    expect(() => parseTmtModel(xml)).toThrow('valid integer Id');
  });
});

describe('parseTmtModel - hardening', () => {
  test('a malicious __proto__ property key does not pollute Object.prototype', () => {
    const xml = minimalModel(
      '<Version>4.3</Version><ThreatInstances><KeyValueOfstringThreatX><Key>k</Key><Value><Id>1</Id>' +
        '<Properties><KeyValueOfstringstring><Key>__proto__</Key><Value>polluted</Value></KeyValueOfstringstring></Properties>' +
        '</Value></KeyValueOfstringThreatX></ThreatInstances>',
    );
    const model = parseTmtModel(xml);
    expect(({} as Record<string, unknown>).polluted).toBeUndefined();
    expect(Object.keys(model.threats[0].properties)).toContain('__proto__');
  });
});
