import { readFileSync } from 'fs';
import { join } from 'path';
import { parseTmtModel } from '.';

const fixture = (name: string) => readFileSync(join(__dirname, '../__fixtures__', name), 'utf-8');

describe('parseTmtModel - Sample_Threat_Model.tm7 (single DFD)', () => {
  const model = parseTmtModel(fixture('Sample_Threat_Model.tm7'));

  test('extracts the single non-empty drawing surface with its GUID and name', () => {
    expect(model.surfaces).toHaveLength(1);
    expect(model.surfaces[0]).toMatchObject({
      guid: 'd8c8aab1-5108-49c5-92a1-b214ba353477',
      name: 'Diagram 1',
      isEmpty: false,
    });
  });

  test('extracts all threat instances from the ThreatInstances dictionary', () => {
    expect(model.threats).toHaveLength(29);
    const threat = model.threats.find((t) => t.id === 7);
    expect(threat).toBeDefined();
    expect(threat?.drawingSurfaceGuid).toBe('d8c8aab1-5108-49c5-92a1-b214ba353477');
    expect(threat?.flowGuid).toBe('f367ac70-74ff-4ba1-abc4-0ac96e350448');
  });

  test('leaves empty model metadata undefined (name/owner are blank in this fixture)', () => {
    expect(model.metadata.threatModelName || undefined).toBeUndefined();
    expect(model.metadata.owner || undefined).toBeUndefined();
  });

  test('extracts a non-empty knowledge base (threat types and property labels)', () => {
    expect(Object.keys(model.knowledgeBase.threatTypes).length).toBeGreaterThan(0);
    expect(Object.keys(model.knowledgeBase.propertyLabels).length).toBeGreaterThan(0);
  });

  test('extracts DFD element names by GUID', () => {
    expect(model.elementNames['41cb799f-434b-4b35-bd8e-8970bb985ec9']).toBe('Generic External Interactor');
  });
});

describe.each([
  'Sample_Threat_Model.tm7',
  'Sample_Threat_Model_Multiple_DFDs.tm7',
  'ContosoCast Threat Model Fully Labeled with AI.tm7',
])('parseTmtModel - %s element names', (name) => {
  test('resolves the source, target, and flow of every threat to a name', () => {
    const model = parseTmtModel(fixture(name));
    const unresolved = model.threats.flatMap((t) => [t.sourceGuid, t.targetGuid, t.flowGuid])
      .filter((guid) => guid && !model.elementNames[guid]);
    expect(unresolved).toEqual([]);
  });
});

